#!/usr/bin/env -S uv run python
"""
Generate the TypeScript view of the API from the server's own schemas.

The server derives /openapi.json and /asyncapi.json from the Pydantic models it validates
against; this script derives the client's types from those same documents. That closes the
last gap where the contract used to be transcribed by hand: a field renamed in
`server/commands.py` reaches the browser's type checker without anyone retyping it.

    uv run python scripts/generate_api_types.py           # write the file
    uv run python scripts/generate_api_types.py --check   # fail if it is out of date

The output is committed, so the frontend keeps working with no build step; --check (wired
into scripts/check.py) is what stops a stale copy being committed.
"""

import argparse
import sys
import typing as tp
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

OUTPUT = PROJECT_ROOT / "seafront/web-static/src/types/seafront-api.d.ts"

HEADER = """\
// Generated by scripts/generate_api_types.py from the server's own /openapi.json and
// /asyncapi.json. Do not edit: run `uv run python scripts/generate_api_types.py` instead.
//
// Every type below is the TypeScript view of a Pydantic model the server validates against,
// so a mismatch here is a mismatch the server would have rejected at runtime.

declare global {

    /**
     * A request body as a caller writes it: everything except the transport envelope, which
     * SeafrontApiClient.post injects. The envelope fields are part of every request model
     * because they are part of every request on the wire.
     */
    type ApiPayload<T> = Omit<T, "target_device" | "lock_token">;
"""

FOOTER = """}

export {};
"""

RESERVED = {"float": "number", "int": "number"}


def ts_name(ref: str) -> str:
    "the component name a $ref points at"
    return ref.rsplit("/", 1)[-1]


def literal(value: tp.Any) -> str:
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    return str(value)


def render(schema: dict[str, tp.Any], indent: int) -> str:
    """one JSON-Schema node as a TypeScript type expression"""
    if not schema:
        return "unknown"

    if "$ref" in schema:
        return ts_name(schema["$ref"])

    if "const" in schema:
        return literal(schema["const"])

    for combinator, joiner in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if combinator in schema:
            parts = [render(s, indent) for s in schema[combinator]]
            # dedupe while keeping order, so `string | string` does not survive
            seen: dict[str, None] = dict.fromkeys(parts)
            return joiner.join(seen)

    if "enum" in schema:
        return " | ".join(literal(v) for v in schema["enum"])

    kind = schema.get("type")

    if isinstance(kind, list):
        return " | ".join(render({**schema, "type": k}, indent) for k in kind)

    if kind == "array":
        item = render(schema.get("items", {}), indent)
        return f"({item})[]" if (" " in item and not item.startswith("{")) else f"{item}[]"

    if kind == "object" or "properties" in schema:
        return render_object(schema, indent)

    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def render_object(schema: dict[str, tp.Any], indent: int) -> str:
    properties = schema.get("properties") or {}
    if not properties:
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"{{ [key: string]: {render(extra, indent)} }}"
        return "{ [key: string]: unknown }" if extra is not False else "{}"

    required = set(schema.get("required", []))
    pad = "    " * (indent + 1)
    lines = ["{"]
    for name, prop in properties.items():
        for comment in doc_lines(prop):
            lines.append(f"{pad}{comment}")
        optional = "" if name in required else "?"
        lines.append(f"{pad}{quote_key(name)}{optional}: {render(prop, indent + 1)};")
    lines.append("    " * indent + "}")
    return "\n".join(lines)


def quote_key(name: str) -> str:
    return name if name.isidentifier() else f'"{name}"'


def doc_lines(schema: dict[str, tp.Any]) -> list[str]:
    text = schema.get("description")
    if not text:
        return []
    body = [line.strip() for line in text.strip().splitlines()]
    if len(body) == 1:
        return [f"/** {body[0]} */"]
    return ["/**", *[f" * {line}" for line in body], " */"]


def collect(*documents: dict[str, tp.Any]) -> dict[str, dict[str, tp.Any]]:
    """
    every component schema across the documents, by name

    A name defined in both must mean the same thing - it is the same Pydantic model reached
    two ways - so a genuine clash is a bug worth stopping for rather than silently picking
    one of the two.
    """
    merged: dict[str, dict[str, tp.Any]] = {}
    for document in documents:
        for name, schema in document.get("components", {}).get("schemas", {}).items():
            if name in merged and merged[name] != schema:
                raise SystemExit(f"schema {name!r} is defined differently in two documents")
            merged[name] = schema
    return merged


def generate() -> str:
    from seafront.server import asyncapi
    from seafront.server.app import make_app

    app = make_app()
    openapi = app.openapi()
    shared = openapi["components"]["schemas"]
    schemas = collect(
        openapi, asyncapi.build(title=app.title, version=app.version, shared=shared)
    )

    invalid = sorted(name for name in schemas if not name.isidentifier())
    if invalid:
        raise SystemExit(
            "these schema names are not usable as TypeScript identifiers: "
            + ", ".join(invalid)
            + "\n(FastAPI splits a model into -Input/-Output when its validation and "
            "serialization schemas differ; see separate_input_output_schemas in server/app.py)"
        )

    out = [HEADER]
    for name in sorted(schemas):
        schema = schemas[name]
        if name in RESERVED:
            continue
        for comment in doc_lines(schema):
            out.append(f"    {comment}")
        out.append(f"    type {name} = {render(schema, 1)};")
        out.append("")
    out.append(FOOTER)
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if the committed file is out of date",
    )
    args = parser.parse_args()

    rendered = generate()

    if not args.check:
        OUTPUT.write_text(rendered)
        print(f"wrote {OUTPUT.relative_to(PROJECT_ROOT)} ({len(rendered.splitlines())} lines)")
        return 0

    current = OUTPUT.read_text() if OUTPUT.exists() else ""
    if current == rendered:
        print(f"{OUTPUT.relative_to(PROJECT_ROOT)} is up to date")
        return 0

    print(
        f"{OUTPUT.relative_to(PROJECT_ROOT)} is out of date.\n"
        "Run: uv run python scripts/generate_api_types.py",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
